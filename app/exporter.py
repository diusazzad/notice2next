"""
Notice2Next - Export Utilities
Formats extracted & verified action items into standard CSV and Markdown checklists.
"""

import csv
import io
from typing import List, Dict, Any


def generate_csv(items: List[Dict[str, Any]]) -> str:
    """Generate a clean, standard CSV from action items."""
    output = io.StringIO()
    writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

    # Write Header
    writer.writerow([
        "Status",
        "Action Item",
        "Responsible Group",
        "Deadline",
        "Fee / Required Documents",
        "Grounding Score",
        "Evidence Quote",
        "Validation Notes"
    ])

    for it in items:
        status_str = "COMPLETED" if it.get("is_completed") else it.get("validation_status", "PENDING")
        writer.writerow([
            status_str,
            it.get("action", ""),
            it.get("assignee", "NOT STATED"),
            it.get("deadline", "NOT STATED"),
            it.get("fee_or_docs", "NOT STATED"),
            f"{int(float(it.get('grounding_score', 0)) * 100)}%",
            it.get("source_quote", ""),
            it.get("validation_notes", "")
        ])

    return output.getvalue()


def generate_markdown(items: List[Dict[str, Any]], title: str = "School Circular Action Checklist") -> str:
    """Generate a markdown formatted checklist with citations."""
    lines = [
        f"# 📋 {title}",
        f"*Generated by Notice2Next — Source-Grounded Teacher Task Assistant*\n",
        "| Status | Action Item | Assigned To | Deadline | Fee/Docs | Evidence Citation |",
        "| :---: | :--- | :--- | :--- | :--- | :--- |"
    ]

    for it in items:
        check = "[x]" if it.get("is_completed") else "[ ]"
        action = it.get("action", "").replace("|", "-")
        assignee = it.get("assignee", "NOT STATED").replace("|", "-")
        deadline = it.get("deadline", "NOT STATED").replace("|", "-")
        fee_docs = it.get("fee_or_docs", "NOT STATED").replace("|", "-")
        quote = it.get("source_quote", "")[:80] + "..." if len(it.get("source_quote", "")) > 80 else it.get("source_quote", "")
        quote = quote.replace("|", "-").replace("\n", " ")

        lines.append(f"| {check} | **{action}** | `{assignee}` | **{deadline}** | {fee_docs} | *\"{quote}\"* |")

    lines.append("\n---\n*Disclaimer: Exact quote matching verifies evidence presence in circular. Teachers should verify items before final execution.*")
    return "\n".join(lines)
