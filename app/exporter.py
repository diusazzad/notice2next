"""
Notice2Next - Export Utilities
Formats extracted & verified action items into standard CSV and Markdown checklists.
Includes defensive escaping against CSV Formula Injection (CWE-1236).
"""

import csv
import io
from typing import List, Dict, Any

DANGEROUS_CSV_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def sanitize_csv_cell(value: Any) -> str:
    """
    Sanitizes cell values to prevent CSV / Spreadsheet Formula Injection (CWE-1236).
    If a string begins with '=', '+', '-', '@', '\\t', or '\\r', an apostrophe prefix
    is added so spreadsheet programs (Excel, Calc, Sheets) treat it strictly as literal text.
    Preserves Unicode, numbers, and harmless text.
    """
    if value is None:
        return ""
    val_str = str(value)
    if val_str.startswith(DANGEROUS_CSV_PREFIXES):
        return f"'{val_str}"
    return val_str


def generate_csv(items: List[Dict[str, Any]]) -> str:
    """
    Generate a clean, standard CSV from action items.
    Applies CWE-1236 formula sanitization to all data cells.
    """
    output = io.StringIO()
    writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)

    # Write Header
    writer.writerow([
        "Status",
        "Action Item",
        "Responsible Group",
        "Deadline",
        "Fee / Required Documents",
        "Grounding Score",
        "Evidence Quote",
        "Validation Notes"
    ])

    for it in items:
        status_str = "COMPLETED" if it.get("is_completed") else it.get("validation_status", "PENDING")
        try:
            score_val = f"{int(float(it.get('grounding_score', 0)) * 100)}%"
        except (ValueError, TypeError):
            score_val = "0%"

        writer.writerow([
            sanitize_csv_cell(status_str),
            sanitize_csv_cell(it.get("action", "")),
            sanitize_csv_cell(it.get("assignee", "NOT STATED")),
            sanitize_csv_cell(it.get("deadline", "NOT STATED")),
            sanitize_csv_cell(it.get("fee_or_docs", "NOT STATED")),
            sanitize_csv_cell(score_val),
            sanitize_csv_cell(it.get("source_quote", "")),
            sanitize_csv_cell(it.get("validation_notes", ""))
        ])

    return output.getvalue()


def generate_markdown(items: List[Dict[str, Any]], title: str = "School Circular Action Checklist") -> str:
    """Generate a markdown formatted checklist with citations and pipe-escaping."""
    lines = [
        f"# 📋 {title}",
        f"*Generated by Notice2Next — Source-Grounded Teacher Task Assistant*\n",
        "| Status | Action Item | Assigned To | Deadline | Fee/Docs | Evidence Citation |",
        "| :---: | :--- | :--- | :--- | :--- | :--- |"
    ]

    for it in items:
        check = "[x]" if it.get("is_completed") else "[ ]"
        action = str(it.get("action") or "").replace("|", "-")
        assignee = str(it.get("assignee") or "NOT STATED").replace("|", "-")
        deadline = str(it.get("deadline") or "NOT STATED").replace("|", "-")
        fee_docs = str(it.get("fee_or_docs") or "NOT STATED").replace("|", "-")
        raw_quote = str(it.get("source_quote") or "")
        quote = raw_quote[:80] + "..." if len(raw_quote) > 80 else raw_quote
        quote = quote.replace("|", "-").replace("\n", " ")

        lines.append(f"| {check} | **{action}** | `{assignee}` | **{deadline}** | {fee_docs} | *\"{quote}\"* |")

    lines.append("\n---\n*Disclaimer: Exact quote matching verifies evidence presence in circular. Teachers should verify items before final execution.*")
    return "\n".join(lines)
